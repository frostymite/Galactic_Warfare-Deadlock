const fs=require('fs'),vm=require('vm'),path=require('path');
let checks=0,fail=[];const ok=(name,v,detail)=>{checks++;if(!v)fail.push({name,detail})};
const box={console,Intl,Date,setTimeout,clearTimeout};box.window=box;box.globalThis=box;vm.createContext(box);
for(const file of ['shipforge-catalog.js','shipforge-visuals.js','shipforge.js','shipforge-world.js','raven-visual.js']){
 vm.runInContext(fs.readFileSync(path.join(__dirname,'../runtime',file),'utf8'),box,{filename:file});
}
const F=box.ShipForge,W=box.DeadlockShipForge,R=box.DeadlockRavenVisual;
ok('ShipForge loaded',!!F);ok('ShipForge world loaded',!!W);ok('Raven visual loaded',!!R);ok('Raven visual version',R.version==='1.0.0',R.version);
const data={character:{name:'Rovan Kes',credits:1000000},ship:{hull:100,hullMax:100,shields:100,shieldsMax:100,fuel:100,fuelMax:100,dogfight:{}},galaxyState:{currentLocationId:'blackglass_station'}};
const st=W.ensure(data);
const baseline=R.partState(data);
ok('Raven state resolves',!!baseline,baseline);
ok('Raven is active persistent ship',baseline.shipId==='raven',baseline.shipId);
const expected={core:'core_twinboom_09',cockpit:'cockpit_armored_05',wing:'wing_outrigger_09',engine:'engine_military_06',weapon:'weapon_rotary_09',cargo:'cargo_modular_08',utility:'utility_smuggler_06'};
for(const [slot,id] of Object.entries(expected))ok('baseline '+slot,baseline.parts[slot]===id,{expected:id,actual:baseline.parts[slot]});
const html=R.render(data,'flight','The Raven');
ok('live renderer returns markup',typeof html==='string'&&html.includes('data-raven-renderer="shipforge-live"'));
ok('renderer uses generated component art',html.includes('data-art="generated"'));
for(const id of Object.values(expected))ok('baseline visual contains '+id,html.includes(id),id);
ok('condition metadata present',/data-raven-condition="\d+"/.test(html),html.slice(0,300));
ok('schematic-independent renderer accepts landed state',R.render(data,'landed','The Raven in hangar').includes('raven-state-landed'));
const beforeSig=baseline.signature;
const inst=W.createInstance(st,'engine_trident_09',{ownerId:'rovan',source:'qa'});
const install=W.install(data,'raven',inst.id);
ok('engine install succeeds',install.ok,install);
const upgraded=R.partState(data),upgradedHtml=R.render(data,'flight','The Raven');
ok('installed engine changes live part state',upgraded.parts.engine==='engine_trident_09',upgraded.parts);
ok('old engine removed from live blueprint',upgraded.parts.engine!=='engine_military_06',upgraded.parts);
ok('visual signature changes after install',upgraded.signature!==beforeSig,{beforeSig,after:upgraded.signature});
ok('upgraded renderer contains new engine',upgradedHtml.includes('engine_trident_09'));
ok('upgraded renderer still uses generated art',upgradedHtml.includes('data-art="generated"'));
const paint=W.setPalette(data,'raven','slate_cyan');ok('paint succeeds',paint.ok,paint);
ok('paint updates visual state',R.partState(data).palette==='slate_cyan',R.partState(data));
ok('critical condition band',R.conditionBand(25)==='critical');
ok('damaged condition band',R.conditionBand(55)==='damaged');
ok('worn condition band',R.conditionBand(75)==='worn');
ok('operational condition band',R.conditionBand(95)==='operational');
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8'),index=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8'),sw=fs.readFileSync(path.join(__dirname,'../sw.js'),'utf8');
ok('app routes Raven through live renderer',app.includes('DeadlockRavenVisual?.render?.(DATA,state,alt)'));
ok('app retains static fallback',app.includes('assets/ships/raven_cutout_v15.svg'));
const iw=index.indexOf('runtime/shipforge-world.js'),ir=index.indexOf('runtime/raven-visual.js'),ia=index.indexOf('app.js');
ok('load order world then Raven then app',iw>=0&&iw<ir&&ir<ia,{iw,ir,ia});
ok('Raven CSS loaded',index.includes('runtime/raven-visual.css'));
ok('Raven runtime cached offline',sw.includes('./runtime/raven-visual.js'));
ok('Raven CSS cached offline',sw.includes('./runtime/raven-visual.css'));
ok('v17.13 cache active',sw.includes('deadlock-v17-13-raven-live-shipforge'));
const result={checks,passed:checks-fail.length,failed:fail.length,failures:fail,baseline,upgraded};
fs.writeFileSync(path.join(__dirname,'raven-visual-results.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));if(fail.length)process.exit(1);
